    const MEMBER_B: &str = "member_b";

    /// Two-user setup with the shared-pool settings repository wired and the
    /// global toggle set to `enabled`. Returns the settings repo so tests can
    /// flip the toggle on the SAME database.
    async fn setup_pool(enabled: bool, cap: i64) -> (ProviderService, Arc<dyn IGlobalSettingsRepository>) {
        let db = init_database_memory().await.unwrap();
        let pool = db.pool().clone();
        sqlx::query(
            "INSERT INTO users (id, user_type, username, password_hash, status, session_generation, created_at, updated_at) \
             VALUES (?, 'local', ?, '', 'active', 0, 1, 1)",
        )
        .bind(MEMBER_B)
        .bind(MEMBER_B)
        .execute(&pool)
        .await
        .unwrap();
        let repo = Arc::new(SqliteProviderRepository::new(pool.clone()));
        let settings_repo = Arc::new(aionui_db::SqliteGlobalSettingsRepository::new(pool));
        settings_repo
            .upsert(&aionui_db::GlobalSettings {
                shared_key_service_enabled: enabled,
                shared_pool_daily_request_cap: cap,
            })
            .await
            .unwrap();
        std::mem::forget(db);
        let svc = ProviderService::new(repo, TEST_KEY).with_global_settings(settings_repo.clone());
        (svc, settings_repo)
    }

