fn validate_create_request(req: &CreateProviderRequest) -> Result<(), SystemError> {
    if let Some(ref id) = req.id {
        validate_id(id)?;
    }
    if req.platform.trim().is_empty() {
        return Err(SystemError::BadRequest("platform is required".into()));
    }
    if req.name.trim().is_empty() {
        return Err(SystemError::BadRequest("name is required".into()));
    }
    // Bedrock auths via bedrock_config (IAM profile / static keys) rather than
    // an HTTP endpoint + bearer key, so baseUrl and apiKey may be empty.
    if req.platform == "bedrock" {
        if req.bedrock_config.is_none() {
            return Err(SystemError::BadRequest(
                "bedrockConfig is required for bedrock platform".into(),
            ));
        }
        if !req.base_url.trim().is_empty() {
            validate_base_url(&req.base_url)?;
        }
    } else {
        validate_base_url(&req.base_url)?;
        if req.api_key.trim().is_empty() {
            return Err(SystemError::BadRequest("apiKey is required".into()));
        }
    }
    Ok(())
}

/// Validate a caller-supplied provider id.
///
/// Accepts any non-empty string up to 128 chars consisting of alphanumerics,
/// dash, or underscore. This is deliberately permissive to accommodate both
/// UUID v4/v7 and legacy short hex ids from the pre-migration frontend.
fn validate_id(id: &str) -> Result<(), SystemError> {
    let trimmed = id.trim();
    if trimmed.is_empty() {
        return Err(SystemError::BadRequest("id must not be empty".into()));
    }
    if trimmed.len() > 128 {
        return Err(SystemError::BadRequest("id must be at most 128 characters".into()));
    }
    if !trimmed
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
    {
        return Err(SystemError::BadRequest(
            "id may only contain alphanumerics, '-', or '_'".into(),
        ));
    }
    Ok(())
}

fn validate_update_request(req: &UpdateProviderRequest) -> Result<(), SystemError> {
    if let Some(ref platform) = req.platform
        && platform.trim().is_empty()
    {
        return Err(SystemError::BadRequest("platform cannot be empty".into()));
    }
    if let Some(ref name) = req.name
        && name.trim().is_empty()
    {
        return Err(SystemError::BadRequest("name cannot be empty".into()));
    }
    if let Some(ref url) = req.base_url
        && !url.trim().is_empty()
    {
        validate_base_url(url)?;
    }
    Ok(())
}

fn validate_base_url(url: &str) -> Result<(), SystemError> {
    if url.trim().is_empty() {
        return Err(SystemError::BadRequest("baseUrl is required".into()));
    }
    if !url.starts_with("http://") && !url.starts_with("https://") {
        return Err(SystemError::BadRequest(
            "baseUrl must start with http:// or https://".into(),
        ));
    }
    Ok(())
}

