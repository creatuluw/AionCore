/// Serialize an optional value to JSON string.
fn serialize_opt<T: serde::Serialize>(val: &Option<T>, field: &str) -> Result<Option<String>, SystemError> {
    val.as_ref()
        .map(serde_json::to_string)
        .transpose()
        .map_err(|e| SystemError::Internal(format!("Failed to serialize {field}: {e}")))
}

/// Serialize a value to JSON string.
fn serialize_json<T: serde::Serialize>(val: &T, field: &str) -> Result<String, SystemError> {
    serde_json::to_string(val).map_err(|e| SystemError::Internal(format!("Failed to serialize {field}: {e}")))
}

/// Deserialize an optional JSON string into a typed value.
pub(crate) fn deserialize_opt<T: DeserializeOwned>(
    json: &Option<String>,
    field: &str,
) -> Result<Option<T>, SystemError> {
    json.as_deref()
        .map(serde_json::from_str)
        .transpose()
        .map_err(|e| SystemError::Internal(format!("Failed to parse {field} JSON: {e}")))
}

