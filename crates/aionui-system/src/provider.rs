/// Business logic for model provider CRUD with API key encryption/masking and
/// shared-key-pool visibility rules.
#[derive(Clone)]
pub struct ProviderService {
    repo: Arc<dyn IProviderRepository>,
    encryption_key: [u8; 32],
    /// Shared-pool settings. `None` (tests/composition paths) means the
    /// shared-key service is OFF: lists show only the caller's own rows.
    global_settings: Option<Arc<dyn IGlobalSettingsRepository>>,
}

impl ProviderService {
    pub fn new(repo: Arc<dyn IProviderRepository>, encryption_key: [u8; 32]) -> Self {
        Self {
            repo,
            encryption_key,
            global_settings: None,
        }
    }

    /// Wire the shared-pool settings repository. Without it the shared-key
    /// service is treated as disabled.
    pub fn with_global_settings(mut self, repo: Arc<dyn IGlobalSettingsRepository>) -> Self {
        self.global_settings = Some(repo);
        self
    }

    /// Read shared-pool settings, falling back to safe defaults when no
    /// repository is wired.
    async fn settings(&self) -> Result<GlobalSettings, SystemError> {
        match self.global_settings.as_ref() {
            Some(repo) => Ok(repo.get().await?),
            None => Ok(GlobalSettings::default()),
        }
    }

    /// List the providers the requesting user effectively sees: their own
    /// rows first, plus shared-pool rows from other users while the
    /// shared-key service is enabled.
    pub async fn list(&self, user_id: &str) -> Result<Vec<ProviderResponse>, SystemError> {
        let settings = self.settings().await?;
        let rows = self
            .repo
            .list_effective(user_id, settings.shared_key_service_enabled)
            .await?;
        rows.into_iter().map(|row| self.row_to_response(row, user_id)).collect()
    }

    /// Create a new provider. The API key is encrypted before storage.
    ///
    /// If `req.id` is `Some`, the caller-supplied id is used (after validation);
    /// otherwise a fresh id is generated by the repository. This supports the
    /// frontend-local-store → backend migration path where existing provider
    /// ids must be preserved.
    ///
    /// Visibility: members always create private rows — requesting `shared`
    /// is rejected with 403. Admins may create shared rows.
    pub async fn create(
        &self,
        user_id: &str,
        is_admin: bool,
        req: CreateProviderRequest,
    ) -> Result<ProviderResponse, SystemError> {
        validate_create_request(&req)?;
        let visibility = resolve_requested_visibility(req.visibility.as_deref(), is_admin)?;

        let encrypted_key = encrypt_string(&req.api_key, &self.encryption_key)?;
        let models_json = serialize_json(&req.models, "models")?;
        let capabilities_json = serialize_json(&req.capabilities, "capabilities")?;
        let model_protocols_json = serialize_opt(&req.model_protocols, "model_protocols")?;
        let model_enabled_json = serialize_opt(&req.model_enabled, "model_enabled")?;
        let model_health_json = serialize_opt(&req.model_health, "model_health")?;
        let model_settings_json = serialize_json(&req.model_settings, "model_settings")?;
        let bedrock_json = serialize_opt(&req.bedrock_config, "bedrock_config")?;
        let trimmed_id = req.id.as_deref().map(str::trim);

        let params = CreateProviderParams {
            id: trimmed_id,
            user_id,
            platform: &req.platform,
            name: &req.name,
            base_url: &req.base_url,
            api_key_encrypted: &encrypted_key,
            visibility: visibility.as_str(),
            models: &models_json,
            enabled: req.enabled,
            capabilities: &capabilities_json,
            context_limit: req.context_limit,
            model_protocols: model_protocols_json.as_deref(),
            model_enabled: model_enabled_json.as_deref(),
            model_health: model_health_json.as_deref(),
            model_settings: &model_settings_json,
            bedrock_config: bedrock_json.as_deref(),
            is_full_url: req.is_full_url,
        };

        let row = self.repo.create(params).await?;
        self.row_to_response(row, user_id)
    }

    /// Update an existing provider. Only provided fields are changed.
    ///
    /// Ownership rule: the owner or an admin. Any other requester gets 404
    /// (row absent) or 403 (row exists but is not theirs), which also covers
    /// members attempting to modify shared rows they do not own. Visibility:
    /// only admins may set `shared`.
    pub async fn update(
        &self,
        user_id: &str,
        is_admin: bool,
        id: &str,
        req: UpdateProviderRequest,
    ) -> Result<ProviderResponse, SystemError> {
        validate_update_request(&req)?;
        if let Some(requested) = req.visibility.as_deref() {
            resolve_requested_visibility(Some(requested), is_admin)?;
        }

        let existing = self.require_accessible_row(user_id, is_admin, id).await?;

        let encrypted_key = req
            .api_key
            .as_deref()
            .map(|k| encrypt_string(k, &self.encryption_key))
            .transpose()?;
        let models_json = serialize_opt(&req.models, "models")?;
        let capabilities_json = serialize_opt(&req.capabilities, "capabilities")?;
        let model_protocols_json = serialize_opt(&req.model_protocols, "model_protocols")?;
        let model_enabled_json = serialize_opt(&req.model_enabled, "model_enabled")?;
        let model_health_json = serialize_opt(&req.model_health, "model_health")?;
        let model_settings_json = serialize_opt(&req.model_settings, "model_settings")?;
        let bedrock_json = serialize_opt(&req.bedrock_config, "bedrock_config")?;

        let params = UpdateProviderParams {
            platform: req.platform.as_deref(),
            name: req.name.as_deref(),
            base_url: req.base_url.as_deref(),
            api_key_encrypted: encrypted_key.as_deref(),
            visibility: req.visibility.as_deref(),
            models: models_json.as_deref(),
            enabled: req.enabled,
            capabilities: capabilities_json.as_deref(),
            context_limit: req.context_limit.map(Some),
            model_protocols: model_protocols_json.as_ref().map(|s| Some(s.as_str())),
            model_enabled: model_enabled_json.as_ref().map(|s| Some(s.as_str())),
            model_health: model_health_json.as_ref().map(|s| Some(s.as_str())),
            model_settings: model_settings_json.as_deref(),
            bedrock_config: bedrock_json.as_ref().map(|s| Some(s.as_str())),
            is_full_url: req.is_full_url,
        };

        let row = self.repo.update(&existing.user_id, id, params).await?;
        self.row_to_response(row, user_id)
    }

    /// Delete a provider by ID. Owner or admin only (same access rule as
    /// [`ProviderService::update`]).
    pub async fn delete(&self, user_id: &str, is_admin: bool, id: &str) -> Result<(), SystemError> {
        let existing = self.require_accessible_row(user_id, is_admin, id).await?;
        self.repo.delete(&existing.user_id, id).await?;
        Ok(())
    }

    // -----------------------------------------------------------------------
    // Internal helpers
    // -----------------------------------------------------------------------

    /// Load the provider row for a modifying request, enforcing the owner-or-
    /// admin rule: a row that does not exist is 404; a row the requester does
    /// not own is 403 unless the requester is an admin.
    async fn require_accessible_row(&self, user_id: &str, is_admin: bool, id: &str) -> Result<Provider, SystemError> {
        let row = self
            .repo
            .find_by_id_global(id)
            .await?
            .ok_or_else(|| SystemError::NotFound(format!("Provider '{id}' not found")))?;
        if row.user_id != user_id && !is_admin {
            // Members may never modify rows they do not own — including
            // shared-pool rows. 403 (not 404) so legitimate clients can tell
            // a permission problem from a deleted provider.
            return Err(SystemError::Forbidden(
                "Only the provider owner or an admin may modify this provider".into(),
            ));
        }
        Ok(row)
    }

    /// Convert a DB row into a response DTO with a masked key hint and
    /// deserialized JSON fields. The plaintext API key NEVER appears in a
    /// response.
    fn row_to_response(&self, row: Provider, requester_id: &str) -> Result<ProviderResponse, SystemError> {
        // Lenient on decryption: a credential encrypted under a rotated/lost
        // key (e.g. one saved during the ELECTRON-3T0 broken session, whose
        // in-memory-only key is gone forever) must not take the whole
        // provider list down. Surface the row with has_key=false so the user
        // can see it and re-enter the key; log at warn for production
        // diagnosability.
        let api_key = match decrypt_string(&row.api_key_encrypted, &self.encryption_key) {
            Ok(key) => key,
            Err(error) => {
                tracing::warn!(
                    provider_id = %row.id,
                    provider_name = %row.name,
                    %error,
                    "provider api_key failed to decrypt; marking has_key=false so the row stays visible for re-entry"
                );
                String::new()
            }
        };
        let has_key = !api_key.is_empty();

        let models: Vec<String> = serde_json::from_str(&row.models)
            .map_err(|e| SystemError::Internal(format!("Failed to parse models JSON: {e}")))?;
        let capabilities = serde_json::from_str(&row.capabilities)
            .map_err(|e| SystemError::Internal(format!("Failed to parse capabilities JSON: {e}")))?;
        let model_protocols: Option<HashMap<String, String>> =
            deserialize_opt(&row.model_protocols, "model_protocols")?;
        let model_enabled: Option<HashMap<String, bool>> = deserialize_opt(&row.model_enabled, "model_enabled")?;
        let model_health = deserialize_opt(&row.model_health, "model_health")?;
        let model_settings = serde_json::from_str(&row.model_settings)
            .map_err(|e| SystemError::Internal(format!("Failed to parse model_settings JSON: {e}")))?;
        let bedrock_config = deserialize_opt(&row.bedrock_config, "bedrock_config")?;

        Ok(ProviderResponse {
            owned: row.user_id == requester_id,
            visibility: row.visibility,
            masked_key: mask_api_key(&api_key),
            has_key,
            id: row.id,
            platform: row.platform,
            name: row.name,
            base_url: row.base_url,
            models,
            enabled: row.enabled,
            capabilities,
            context_limit: row.context_limit,
            model_protocols,
            model_enabled,
            model_health,
            model_settings,
            bedrock_config,
            is_full_url: row.is_full_url,
            created_at: row.created_at,
            updated_at: row.updated_at,
        })
    }
}

/// Resolve a requested pool visibility against the caller's privilege.
///
/// `None`/empty and `"private"` are always allowed. `"shared"` requires the
/// caller to be an admin; members requesting shared get 403. Unknown values
/// are 400.
fn resolve_requested_visibility(requested: Option<&str>, is_admin: bool) -> Result<ProviderVisibility, SystemError> {
    let Some(requested) = requested.map(str::trim).filter(|v| !v.is_empty()) else {
        return Ok(ProviderVisibility::Private);
    };
    let visibility = ProviderVisibility::parse(requested).ok_or_else(|| {
        SystemError::BadRequest(format!("visibility must be 'private' or 'shared', got '{requested}'"))
    })?;
    if visibility == ProviderVisibility::Shared && !is_admin {
        return Err(SystemError::Forbidden(
            "Only admins may share a provider into the shared key pool".into(),
        ));
    }
    Ok(visibility)
}

